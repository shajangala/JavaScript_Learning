// creating string using single,double quotes and backticks
let str1 = "Hello";
console.log(str1);
console.log(typeof str1);

let str2 = 'hello';
console.log(str2);
console.log(typeof str2);

let str3 = `hello`;
console.log(str3);
console.log(typeof str3);

// creating string using string constructor
let num = 123;
let str4 = String(num);
console.log(str4);
console.log(typeof str4);

// creating strings using new keyword
let str5 = new String("hello"); 
console.log(str5);
console.log(typeof str5);




