// Comparsion operator - These are used to compare two values and return a boolean value.

console.log("Greatet than: ",(10 > 3));
console.log("Less than: ",(10 < 3));
console.log("Greatet than equal to: ",(10 >= 3));
console.log("Less than equal to: ",(10 <= 3));
console.log("Not equal to: ",(10 != 3));
console.log("equal to: ",(10 == "10"));
console.log("Strict equal to: ",("10" === 10));

